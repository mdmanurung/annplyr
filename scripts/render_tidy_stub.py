"""Generate ``src/annplyr/_tidy.pyi`` from the accessor.

The verbs on :class:`~annplyr.TidyAnnData` are attached at runtime from
:class:`~annplyr.AnnplyrAccessor` so there is one implementation and no
signature drift. Type checkers cannot see runtime-attached methods, so this
script renders a stub from the same source. Run with ``--write`` after an
intentional signature change; ``--check`` is enforced by the test suite.
"""

from __future__ import annotations

import argparse
import difflib
import inspect
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))


from anndata import AnnData  # noqa: E402

from annplyr import AnnplyrAccessor  # noqa: E402

TARGET = ROOT / "src" / "annplyr" / "_tidy.pyi"

PREAMBLE = '''"""Type stub for :mod:`annplyr._tidy`. Generated by scripts/render_tidy_stub.py."""

from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from typing import Any, TypeVar

import pandas as pd
from anndata import AnnData

import annplyr
from annplyr._accessor import AnnplyrAccessor
from annplyr._expr import AnnplyrExpr
from annplyr._grouped import GroupedAnnData
from annplyr._typing import (
    Axis,
    Expression,
    JoinBy,
    JoinInput,
    JoinMultiple,
    JoinRelationship,
    JoinUnmatched,
    NaMatches,
    Selector,
    Source,
    SourceSelectors,
)

T = TypeVar("T")

class TidyAnnData(AnnData):
    @property
    def ap(self) -> annplyr.AnnplyrAccessor: ...
    @classmethod
    def wrap(cls, source: Any) -> Any: ...
    def to_anndata(self) -> AnnData: ...
    def __getitem__(self, index: Any) -> Any: ...
    def copy(self, *args: Any, **kwargs: Any) -> Any: ...
    def to_memory(self, *args: Any, **kwargs: Any) -> Any: ...
    def rename_categories(self, *args: Any, **kwargs: Any) -> Any: ...
    def concatenate(self, *args: Any, **kwargs: Any) -> Any: ...

# fmt: off
'''

EPILOGUE = """
# fmt: on

SHADOWED_VERBS: dict[str, str]

def install_verbs(accessor_cls: type[AnnplyrAccessor]) -> None: ...
"""

#: Declared by hand in the stub preamble, so they must not also be rendered.
MANUAL = frozenset(
    {
        "ap",
        "wrap",
        "to_anndata",
        "__getitem__",
        "copy",
        "to_memory",
        "rename_categories",
        "concatenate",
    }
)


def _annotation(value: Any) -> str:
    if value is inspect.Parameter.empty:
        return "Any"
    if isinstance(value, str):
        return value
    return repr(value)


def _render_verb(name: str, method: Any) -> str:
    signature = inspect.signature(method)
    pieces: list[str] = []
    for parameter in signature.parameters.values():
        if parameter.name == "self":
            continue
        text = parameter.name
        if parameter.kind is inspect.Parameter.VAR_POSITIONAL:
            text = f"*{text}"
        elif parameter.kind is inspect.Parameter.VAR_KEYWORD:
            text = f"**{text}"
        annotation = _annotation(parameter.annotation)
        if parameter.default is inspect.Parameter.empty:
            pieces.append(f"{text}: {annotation}")
        else:
            default = parameter.default
            rendered = repr(default) if isinstance(default, str | int | float | bool | type(None)) else "..."
            pieces.append(f"{text}: {annotation} = {rendered}")
    returns = _annotation(signature.return_annotation).replace("AnnDataWithAnnplyr", "TidyAnnData")
    parameters = ", ".join(["self", *pieces])
    return f"    def {name}({parameters}) -> {returns}: ..."


def render() -> str:
    """Render the complete stub as source text."""
    verbs = [
        (name, method)
        for name, method in inspect.getmembers(AnnplyrAccessor, predicate=inspect.isfunction)
        if not name.startswith("_") and name not in MANUAL and not hasattr(AnnData, name)
    ]
    body = "\n".join(_render_verb(name, method) for name, method in verbs)
    return f"{PREAMBLE}\n{body}\n{EPILOGUE}"


def main() -> int:
    """Write or verify the committed stub."""
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render()
    if args.write:
        TARGET.write_text(rendered)
        return 0
    current = TARGET.read_text() if TARGET.exists() else ""
    if current == rendered:
        return 0
    sys.stderr.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            rendered.splitlines(keepends=True),
            fromfile=str(TARGET),
            tofile="generated",
        )
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
